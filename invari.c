#include <time.h>
#include <unistd.h>

#include "invari.h"

#define ITER_DEFAULT 100

/*
 * variant: internal helper functions to wrap variants generically.
 */
struct variant _wrap_int(int i) {
  return (struct variant){.T = VARIANT_INT, .i = i};
}
struct variant _wrap_double(double d) {
  return (struct variant){.T = VARIANT_DOUBLE, .d = d};
}
struct variant _wrap_str(char *str) {
  return (struct variant){.T = VARIANT_STR, .str = str};
}
struct variant _wrap_ptr(void *ptr) {
  return (struct variant){.T = VARIANT_PTR, .ptr = ptr};
}

int variant_copy(struct arena *a, struct variant *v) {
  switch (v->T) {
    // We don't copy integers or doubles since they are part of the struct.
  case VARIANT_INT:
  case VARIANT_DOUBLE:
  case VARIANT_NONE:
    return 1;

    // Default behavior for strings is to deep copy if it exists.
  case VARIANT_STR:

    if (!v->str)
      return 1;

    size_t n = strlen(v->str) + 1;
    char *ptr = aalloc(a, n);

    assert(ptr);

    memcpy(ptr, v->str, n);
    v->str = ptr;

    return 1;

  case VARIANT_PTR:
    return 0;
  }

  return 1;
}

/* Default printing behavior for each variant type. */
void variant_print(struct variant *v) {
  switch (v->T) {
  case VARIANT_INT:
    printf("%d", v->i);
    break;

  case VARIANT_DOUBLE:
    printf("%f", v->d);
    break;

  case VARIANT_STR:
    printf("\"%s\"", v->str);
    break;

  case VARIANT_PTR:
    printf("%p", v->ptr);
    break;

  default:
    printf("<none>");
  }
}

/*
 * instance
 */
#define instance_init(x, y) ((struct instance){.name = (x), .v = (y)})

/* Primitive "dynamic" array to construct instance array. */
void _array_grow(void **A, int n, size_t t) { *A = realloc(*A, n * t); }
#define array_grow(A, n) (_array_grow((void **)(A), (n) + 1, sizeof((*(A))[0])))
#define array_push(A, n, e) (array_grow((A), (n)), (*(A))[(n)] = (e))

/* Initialize our variant lookup table. */
int instance_table_init(struct instance **i, struct input_space *space) {
  int n;
  for (n = 0; (space + n)->name; n++) {
    array_push(i, n, instance_init((space + n)->name, (struct variant){0}));
  }
  array_push(i, n, (struct instance){0});

  return n;
}

/* Populate instance table with values generated by input_space */
void instance_table_gen(struct instance *i, struct input_space *space) {
  struct input_space *entry = NULL;
  for (int n = 0; (entry = space + n)->name; n++) {
    i[n].v = entry->gen ? entry->gen() : (struct variant){0};
  }
}

/* Search for a variant by instance name. */
struct variant instance_get(struct instance *A, char *k) {
  for (int i = 0; (A + i)->name; i++) {
    if (!strcmp((A + i)->name, k))
      return (A + i)->v;
  }

  return (struct variant){0};
}

int instance_copy(struct arena *a, struct instance *i) {
  if (i->copy)
    return i->copy(a, &i->v);

  return variant_copy(a, &i->v);
}

/*
 * utilities
 */

/* Get current time with nanosecond precision. */
double timer(void) {
  struct timespec ts;
  clockid_t id = CLOCK_MONOTONIC_RAW;

  clock_gettime(id, &ts);

  return (double)ts.tv_sec + (double)ts.tv_nsec / 1.0e9;
}

/* Timing statistics helper functions. */
static double mean(double old, double t, int n) {
  return ((old * n) + t) / (n + 1);
}
static inline double max(double x, double y) { return x > y ? x : y; }

/* FNV-1a hashing algorithm. Further reading:
 * https://en.wikipedia.org/wiki/Fowler-Noll-Vo_hash_function */
static unsigned int hash(char *str) {
  unsigned long hash = 0xcbf29ce484222325; // FNV offset basis
  unsigned long prime = 0x100000001b3;     // FNV prime

  for (int i = 0; str[i] != '\0'; i++) {
    hash ^= str[i];
    hash *= prime;
  }

  return (unsigned int)((hash >> 32) ^ hash);
}

static unsigned int nrand() {
  unsigned int r = 0;
  if (getrandom((void *)&r, sizeof(r), 0) < 0)
    r = time(NULL);

  return r;
}

/*
 * Bump allocate in arena.
 */
void *aalloc(struct arena *a, size_t size) {
  if (a->off + size > a->cap)
    return NULL;

  void *ptr = a->base + a->off;
  a->off += size;

  return ptr;
}

/*
 * report: information to output upon test completion.
 */
struct report {
  bool ok;
  struct {
    double mean;
    double max;
  } t;
  int ac[2];
  int signal;
  struct {
    int n;
    struct instance *i;
    int it;
  } ce;
};

void report_record_result(struct report *r, bool ok, double elapsed, int n) {
  r->ok &= ok;
  r->ac[ok]++;
  r->t.mean = mean(r->t.mean, elapsed, n);
  r->t.max = max(r->t.max, elapsed);
}

void report_record_ce(struct arena *a, struct report *r,
                      struct instance *instances, int n) {
  r->ce.n = n + 1; // We copy n + 1 elements in order to include the sentinel
                   // value we've already constructed.
  size_t size = sizeof(struct instance) * r->ce.n;
  r->ce.i = aalloc(a, size);
  memcpy(r->ce.i, instances, size);

  for (int i = 0; i <= n; i++) {
    instance_copy(a, r->ce.i + i);
  }
}

void report_process_status(struct report *r, int status) {

  if (!WIFSIGNALED(status))
    return;

  r->ok = false;
  r->ac[false]++;
  r->signal = WTERMSIG(status);
}

static char *result_str[] = {
    [false] = "FAIL",
    [true] = "OK",
};

/*
 * Output
 */
#define RESET "\e[0m"
#define BOLD "\e[1m"
#define RED "\e[1;31m"
#define GREEN "\e[1;32m"
void result_print_header(struct property *prop, struct report *r) {
  int passed = r->ac[true];
  int failed = r->ac[false];
  int total = passed + failed;

  printf("\n"
         "  %s%-4s%s %s%s%s\n"
         "       %d out of %d passed\n"
         "       seed:    0x%08x\n",
         r->ok ? GREEN : RED, result_str[r->ok], RESET, BOLD, prop->name, RESET,
         passed, total, prop->seed);
}

void result_print_timing(struct report *r) {
  printf("       mean:    %.9fs\n"
         "       worst:   %.9fs\n",
         r->t.mean, r->t.max);
}

#define SIGNAL RED "!" RESET
void result_print_signal(struct report *r) {
  printf("     " SIGNAL " signal:  %s\n", strsignal(r->signal));
}

void result_print_ce(struct report *r) {
  printf("\n"
         "       counterexample\n");

  struct instance *curr;
  for (int i = 0; (curr = (r->ce.i + i))->name; i++) {
    printf("         %s = ", curr->name);
    variant_print(&curr->v);
    printf("\n");
  }
}

void result_print(struct property *prop, struct report *r) {

  result_print_header(prop, r);

  if (!r->signal)
    result_print_timing(r);
  else
    result_print_signal(r);

  if (r->ce.i)
    result_print_ce(r);
}

void result_summary_print(int ac[2]) {
  int passed = ac[true];
  int failed = ac[false];

  printf("\n"
         "  %s**** summary%s\n"
         "       passed: %d\n"
         "       failed: %d\n"
         "       total:  %d\n",
         BOLD, RESET, passed, failed, passed + failed);
}

struct shared {
  struct report r;
  struct arena a;
};

/*
 * Verify a property.
 */
void run(struct property *prop, struct shared *shm) {

  struct instance *instances = NULL;
  struct input_space *entry = NULL;
  int n = 0;

  struct report *r = &shm->r;
  struct arena *a = &shm->a;

  // Construct a lookup table for arguments and their instances.
  if (prop->space) {
    n = instance_table_init(&instances, prop->space);
  }

  *r = (struct report){.ok = true};

  srand(prop->seed);

  // Evaluate the predicate the amount of times configured, recording the
  // iteration in the report.
  bool ok = false;
  int iter = prop->iterations ? prop->iterations : ITER_DEFAULT;
  for (int i = 0; i < iter; i++) {
    void *ctx = prop->prestate ? prop->prestate() : NULL;

    // Populate lookup table using output from generator functions.
    if (prop->space) {
      instance_table_gen(instances, prop->space);
    }

    double elapsed = timer();

    ok = prop->predicate(instances, ctx);

    elapsed = timer() - elapsed;

    // Record counterexample if this is our first failure.
    if (prop->space && !ok && !r->ce.i) {
      report_record_ce(a, r, instances, n);
    }

    report_record_result(r, ok, elapsed, i);

    if (prop->poststate)
      prop->poststate(ctx);
  }

  if (instances)
    free(instances);
}

/*
 * Execute property test in separate process.
 */
void run_isolated(struct property *prop, struct shared *shm) {

  pid_t cpid = fork();

  if (cpid == 0) {
    run(prop, shm);

    exit(EXIT_SUCCESS);
  }

  if (cpid == -1) {
    exit(EXIT_FAILURE);
  }

  int status;
  waitpid(cpid, &status, 0);

  report_process_status(&shm->r, status);
}

/*
 * Verify each property in a specification and collect analytics.
 */
int run_spec(struct specification spec) {
  int ac[2] = {0};

  // If no seed is set, generate a seed using a hash of the specification name
  // and bytes from /dev/urandom. If getrandom() fails, we use the current
  // time instead.
  if (!spec.seed) {
    spec.seed = nrand() ^ hash(spec.name);
  }

  printf("Verifying '%s' specification with seed 0x%08x\n", spec.name,
         spec.seed);

  struct property *prop = NULL;
  for (int i = 0; (prop = spec.props + i)->name; i++) {
    // Derive per property seed based on spec seed. Respect explicitly set
    // seeds.
    if (!prop->seed)
      prop->seed = spec.seed ^ hash(prop->name);

    size_t size = 1024 * 1024 * 64;
    struct shared *shm = mmap(NULL, size, PROT_READ | PROT_WRITE,
                              MAP_SHARED | MAP_ANONYMOUS, -1, 0);
    shm->a.cap = size - sizeof(struct shared);
    struct report *r = &shm->r;

    run_isolated(prop, shm);

    result_print(prop, r);

    ac[r->ok]++;

    munmap(shm, size);
  }

  result_summary_print(ac);
  return 0;
};
